const catalog: Record<AppLanguage, TraceMessages> = { en, "zh-CN": zh };

export function traceMessagesFor(language: AppLanguage): TraceMessages {
	return catalog[language];
}

export function traceStatus(t: TraceMessages, status: string): string {
	return Object.hasOwn(t.statuses, status) ? t.statuses[status]! : status;
}
