export type Messages = (typeof messages)["en"];

export function messagesFor(language: AppLanguage): Messages {
	return messages[language];
}

export function uiPlatform(hint: string): UiPlatform {
	const value = hint.toLowerCase();
	if (value === "darwin" || value.includes("mac")) return "mac";
	if (value === "win32" || value.includes("windows")) return "windows";
	return "other";
}

export function assetTypeLabel(t: Messages, type: string): string {
	if (type === "image" || type === "video" || type === "audio" || type === "text" || type === "other") return t.assetType[type];
	return type;
}

export function rawStatusLabel(t: Messages, status: string): string {
	if (status === "ready") return t.status.ready;
	if (status === "embedding") return t.status.embedding;
	if (status === "describing") return t.status.describing;
	if (status === "error" || status === "failed") return t.status.error;
	return status;
}
