import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { expect, test } from "./loom.ts";

test("Markdown find shows results and replacement feedback with advanced controls collapsed", async ({ loomPage: page, electronApp }) => {
	test.skip(!electronApp, "isolated Electron required");
	await page.emulateMedia({ reducedMotion: "no-preference" });
	const root = () => page.evaluate(async () => (await window.loom.getLibrarySnapshot()).rootPath);
	await expect.poll(root).toBeTruthy();
	const file = join((await root())!, "find.md");
	await writeFile(file, "beta\n\nsecond beta\n\nthird beta\n");
	await page.locator(".library-sidebar .asset-row").filter({ hasText: "find.md" }).click();
	const editor = page.getByRole("textbox", { name: "Edit find.md" });
	const toolbar = page.getByRole("toolbar", { name: "Markdown view" });
	const findGroup = toolbar.getByRole("group", { name: "Find in document" });
	const findButton = toolbar.getByRole("button", { name: "Find in document" });
	const bar = toolbar.locator(".markdown-find");
	const field = bar.getByRole("textbox", { name: "Find in document" });
	await expect(findButton).toHaveAttribute("aria-expanded", "false");
	await expect(findButton).toHaveText("");
	await findGroup.evaluate((group) => {
		group.addEventListener("transitionrun", (event) => {
			if (event instanceof TransitionEvent && event.target === group && event.propertyName === "flex-basis") {
				group.setAttribute("data-observed-expansion", "true");
			}
		});
	});
	await findButton.click();
	await expect(field).toBeFocused();
	await expect(findGroup).toHaveAttribute("data-observed-expansion", "true");
	await expect(bar.locator(".markdown-find-search").getByRole("button", { name: "Find in document" })).toHaveAttribute("aria-expanded", "true");
	await findButton.click();
	await expect(bar).toHaveCount(0);
	await expect(findButton).toHaveAttribute("aria-expanded", "false");
	await page.emulateMedia({ reducedMotion: "reduce" });
	await expect(findGroup).toHaveCSS("transition-duration", "0s");
	await editor.press("ControlOrMeta+f");
	await expect(findButton).toHaveAttribute("aria-expanded", "true");
	const status = bar.getByRole("status");
	const options = bar.getByRole("button", { name: "Find options" });
	const next = bar.getByRole("button", { name: "Next match" });
	const replace = bar.locator("input[name=replace]");
	await expect(field).toBeFocused();
	await expect(toolbar.locator(".cm-panels-top:has(> .markdown-find)")).toHaveCSS("border-bottom-width", "0px");
	await expect(bar.locator(".markdown-find-controls")).toHaveCSS("column-gap", "2px");
	const coarsePointer = await page.evaluate(() => matchMedia("(pointer: coarse)").matches);
	await expect(findGroup).toHaveCSS("flex-basis", "336px");
	const searchFrame = bar.locator(".markdown-find-search");
	await expect(searchFrame).toHaveCSS("height", coarsePointer ? "44px" : "24px");
	await expect(searchFrame).toHaveCSS("outline-offset", "-2px");
	const focusedOutline = await searchFrame.evaluate((frame) => getComputedStyle(frame).outlineColor);
	await expect(next).toHaveCSS("width", coarsePointer ? "44px" : "24px");
	await expect(next).toHaveCSS("margin", "0px");
	const fieldWidth = () => field.evaluate((input) => input.getBoundingClientRect().width);
	const initialWidth = await fieldWidth();
	await expect(options).toHaveAttribute("aria-expanded", "false");
	await expect(replace).toBeHidden();
	await field.fill("beta");
	await expect(status).toHaveText("Match 1 of 3");
	const count = bar.locator(".markdown-find-search").getByText("1 / 3", { exact: true });
	await expect(count).toBeVisible();
	await next.focus();
	await count.click();
	await expect(field).toBeFocused();
	expect(await fieldWidth()).toBe(initialWidth);
	await expect(editor.locator(".cm-searchMatch-selected")).toHaveText("beta");
	await field.dispatchEvent("keydown", { key: "Enter", isComposing: true });
	await expect(status).toHaveText("Match 1 of 3");
	await field.press("Enter");
	await expect(status).toHaveText("Match 2 of 3");
	await field.press("Shift+Enter");
	await expect(status).toHaveText("Match 1 of 3");
	await field.fill("missing");
	await expect(status).toHaveText("No matches");
	expect(await fieldWidth()).toBe(initialWidth);
	await expect(next).toBeDisabled();

	const editorTop = (await editor.boundingBox())?.y;
	await options.click();
	const advanced = bar.getByRole("group", { name: "Find options" });
	await expect(advanced).toBeVisible();
	expect((await editor.boundingBox())?.y).toBe(editorTop);
	await expect(options).toHaveAttribute("aria-expanded", "true");
	const regex = advanced.getByRole("checkbox", { name: "Regex" });
	await regex.press("Escape");
	await expect(advanced).toBeHidden();
	await expect(bar).toBeVisible();
	await expect(options).toHaveAttribute("aria-expanded", "false");
	await options.click();
	await field.click();
	await expect(advanced).toBeHidden();
	await options.click();
	await expect(replace).toBeVisible();
	await regex.check();
	await field.fill("[");
	await expect(field).toHaveAttribute("aria-invalid", "true");
	await expect(status).toHaveText("Invalid regex");
	await expect(searchFrame).not.toHaveCSS("outline-color", focusedOutline);
	expect(await fieldWidth()).toBe(initialWidth);
	await regex.uncheck();
	await field.fill("beta");
	await expect(status).toHaveText("Match 1 of 3");
	await replace.fill("gamma");
	await bar.getByRole("button", { name: "Replace all" }).click();
	await expect(bar.locator(".markdown-find-feedback")).toHaveText("replaced 3 matches.");
	await expect(status).toHaveText("No matches");
	await expect.poll(() => readFile(file, "utf8")).toBe("gamma\n\nsecond gamma\n\nthird gamma\n");

	await page.getByRole("button", { name: "Reading mode", exact: true }).click();
	await expect(bar).toBeVisible();
	await expect(field).toHaveValue("beta");
	await expect(replace).toHaveCount(0);
	await field.press("Escape");
	await expect(bar).toHaveCount(0);
	await expect(findButton).toHaveAttribute("aria-expanded", "false");
	await expect(editor).toBeFocused();
});
