import { readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { expect, test } from "./loom.ts";

test("COS settings, latest cloud copy, interrupted retry, deletion and restore work through Electron IPC", async ({ loomPage: page, electronApp }) => {
	test.skip(!electronApp, "isolated Electron required");
	test.setTimeout(65_000);
	await expect.poll(async () => (await page.evaluate(() => window.loom.getLibrarySnapshot())).rootPath).toBeTruthy();
	const root = (await page.evaluate(() => window.loom.getLibrarySnapshot())).rootPath!;
	await writeFile(join(root, "cloud-note.md"), "keep my library metadata");
	await writeFile(join(root, "obsolete.md"), "delete this on the next update");
	await expect.poll(async () => (await page.evaluate(() => window.loom.getLibrarySnapshot())).assets.length).toBe(2);
	const assetId = (await page.evaluate(() => window.loom.getLibrarySnapshot())).assets.find((asset) => asset.filename === "cloud-note.md")!.assetId;
	await page.evaluate(async (id) => { await window.loom.setFavorite(id, true); await window.loom.addAssetTag(id, "cloud-test"); }, assetId);
	// Replace only the provider boundary; lifecycle, filesystem, encryption and IPC remain real.
	await electronApp!.evaluate(async ({ app, dialog }, parent) => {
		const { createRequire } = process.getBuiltinModule("node:module");
		const require = createRequire(`${app.getAppPath()}/package.json`);
		const { readFile } = require("node:fs/promises") as typeof import("node:fs/promises");
		const COS = require("cos-nodejs-sdk-v5");
		const { createHash } = require("node:crypto") as typeof import("node:crypto");
		const objects = new Map<string, Buffer>();
		(globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects = objects;
		const control: { suffix?: string; fail?: () => void; uploaded: string[] } = { uploaded: [] };
		(globalThis as typeof globalThis & { cloudUploadControl: typeof control }).cloudUploadControl = control;
		COS.prototype.headObject = async ({ Key }: { Key: string }) => { const bytes = objects.get(Key); if (!bytes) throw { statusCode: 404 }; return { headers: { "content-length": String(bytes.length), etag: createHash("sha256").update(bytes).digest("hex") } }; };
		COS.prototype.deleteObject = async ({ Key }: { Key: string }) => { objects.delete(Key); return {}; };
		COS.prototype.uploadFile = ({ Key, FilePath, onProgress }: { Key: string; FilePath: string; onProgress?: (value: { loaded: number }) => void }, callback: (error: { code: string; statusCode: number } | null, result: object) => void) => {
			if (control.suffix && Key.endsWith(control.suffix)) { control.fail = () => callback({ code: "AccessDenied", statusCode: 403 }, {}); return; }
			void readFile(FilePath).then((bytes) => { objects.set(Key, bytes); control.uploaded.push(Key); onProgress?.({ loaded: bytes.length }); callback(null, {}); });
		};
		COS.prototype.getBucket = async ({ Prefix }: { Prefix: string }) => ({ Contents: [...objects.keys()].filter((Key) => Key.startsWith(Prefix)).map((Key) => ({ Key })), IsTruncated: "false" });
		COS.prototype.getObjectUrl = ({ Key }: { Key: string }, callback: (error: null, result: { Url: string }) => void) => { callback(null, { Url: `https://loom-cos.test/${encodeURIComponent(Key)}` }); return ""; };
		const originalFetch = globalThis.fetch;
		globalThis.fetch = (async (input: string | URL | Request, options?: RequestInit) => {
			if (typeof input === "string" && input.startsWith("https://loom-cos.test/")) {
				const bytes = objects.get(decodeURIComponent(new URL(input).pathname.slice(1)));
				return new Response(bytes ? new Uint8Array(bytes) : null, { status: bytes ? 200 : 404 });
			}
			return originalFetch(input, options);
		}) as typeof fetch;
		dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [parent] })) as typeof dialog.showOpenDialog;
	}, dirname(root));
	await page.getByRole("button", { name: "Settings", exact: true }).click();
	const settings = page.locator(".settings-dialog");
	await settings.getByRole("tab", { name: "Cloud backup", exact: true }).click();
	const provider = settings.getByRole("combobox", { name: "Storage provider", exact: true });
	await expect(provider).toHaveValue("none");
	await expect(settings.getByLabel("SecretId", { exact: true })).toHaveCount(0);
	await expect(settings.getByRole("button", { name: "Update cloud copy", exact: true })).toHaveCount(0);
	await expect(settings.getByRole("button", { name: "Test connection", exact: true })).toHaveCount(0);
	await provider.selectOption("cos");
	await expect(settings.getByLabel("Backup prefix", { exact: true })).toHaveCount(0);
	await settings.getByLabel("Bucket", { exact: true }).fill("my-loom-1250000000");
	await settings.getByLabel("SecretId", { exact: true }).fill("e2e-secret-id");
	await settings.getByLabel("SecretKey", { exact: true }).fill("e2e-secret-key");
	await settings.getByRole("button", { name: "Save", exact: true }).click();
	await expect(settings.getByRole("button", { name: "Test connection", exact: true })).toBeEnabled();
	await expect(settings.getByLabel("SecretId", { exact: true })).toHaveValue("e2e-secret-id");
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveValue("e2e-secret-key");
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveAttribute("type", "password");
	await settings.getByRole("button", { name: "Show SecretKey", exact: true }).click();
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveAttribute("type", "text");
	await settings.getByRole("button", { name: "Hide SecretKey", exact: true }).click();
	await settings.getByRole("button", { name: "Close settings", exact: true }).click();
	await page.getByRole("button", { name: "Settings", exact: true }).click();
	await settings.getByRole("tab", { name: "Cloud backup", exact: true }).click();
	await expect(settings.getByLabel("SecretId", { exact: true })).toHaveValue("e2e-secret-id");
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveValue("e2e-secret-key");
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveAttribute("type", "password");
	// Editing one field retains the saved value of the other field.
	await settings.getByLabel("SecretKey", { exact: true }).fill("e2e-secret-key-updated");
	await settings.getByRole("button", { name: "Save", exact: true }).click();
	await expect(settings.getByRole("button", { name: "Test connection", exact: true })).toBeEnabled();
	const userData = await electronApp!.evaluate(({ app }) => app.getPath("userData"));
	expect(await readFile(join(userData, "cloud-backup.json"), "utf8")).not.toContain("e2e-secret");
	expect(JSON.parse(await readFile(join(userData, "cloud-backup.json"), "utf8")).provider).toBe("cos");
	expect(JSON.parse(await readFile(join(userData, "cloud-backup.json"), "utf8"))).not.toHaveProperty("prefix");
	expect((await page.evaluate(() => window.loom.getCloudBackup())).config.provider).toBe("cos");
	await settings.getByRole("button", { name: "Test connection", exact: true }).click();
	await expect(settings.getByRole("region", { name: "Cloud backup progress" })).toContainText("Completed");
	const localStatus = settings.getByRole("region", { name: "Current library backup", exact: true });
	await expect(localStatus).toContainText("No successful backup recorded on this computer");
	await settings.getByRole("button", { name: "Preview changes", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("completed");
	await expect(localStatus.locator(".cloud-change-list li").filter({ hasText: "cloud-note.md" })).toContainText("Added");
	expect(await electronApp!.evaluate(() => (globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects.size)).toBe(0);
	await settings.getByRole("button", { name: "Update cloud copy", exact: true }).click();
	await settings.getByRole("button", { name: "Close settings", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("completed");
	await page.getByRole("button", { name: "Settings", exact: true }).click();
	await settings.getByRole("tab", { name: "Cloud backup", exact: true }).click();
	await expect(settings.getByLabel("SecretId", { exact: true })).toHaveValue("e2e-secret-id");
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveValue("e2e-secret-key-updated");
	const previous = (await page.evaluate(() => window.loom.getCloudBackup())).libraries[0]!;
	expect((await page.evaluate(() => window.loom.getCloudBackup())).localLibrary?.lastBackupAt).toBe(previous.updatedAt);
	const remoteRoot = `loom/libraries/${previous.libraryId}/`;
	let keys = await electronApp!.evaluate(() => [...(globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects.keys()]);
	expect(keys).toContain(`${remoteRoot}cloud-note.md`);
	expect(keys).toContain(`${remoteRoot}obsolete.md`);
	expect(keys.some((key) => key.startsWith("loom/objects/") || key.startsWith("loom/records/"))).toBe(false);
	await electronApp!.evaluate(() => { const g = globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer>; cloudSavedCopy: Map<string, Buffer> }; g.cloudSavedCopy = new Map(g.cloudObjects); });
	await rm(join(root, "obsolete.md"));
	await writeFile(join(root, "cloud-note.md"), "latest cloud copy");
	await settings.getByRole("button", { name: "Preview changes", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("completed");
	await expect(localStatus.locator(".cloud-change-list li").filter({ hasText: "cloud-note.md" })).toContainText("Modified");
	await expect(localStatus.locator(".cloud-change-list li").filter({ hasText: "obsolete.md" })).toContainText("Deleted");
	await localStatus.scrollIntoViewIfNeeded();
	await page.screenshot({ path: test.info().outputPath("cloud-preview.png") });
	expect(await electronApp!.evaluate((_electron, key) => (globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects.has(key), `${remoteRoot}obsolete.md`)).toBe(true);
	await writeFile(join(root, "after-preview.txt"), "written after checking");
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).localLibrary?.preview?.stale).toBe(true);
	await electronApp!.evaluate(() => { (globalThis as typeof globalThis & { cloudUploadControl: { suffix?: string } }).cloudUploadControl.suffix = "/cloud-note.md"; });
	await settings.getByRole("button", { name: "Update cloud copy", exact: true }).click();
	// Hold one provider request until another file is durably checkpointed, then fail it.
	await expect.poll(async () => {
		const directory = join(userData, "cloud-backup-progress");
		const names = await readdir(directory, { recursive: true });
		for (const name of names.filter((name) => name.endsWith(".jsonl"))) {
			const log = await readFile(join(directory, name), "utf8");
			if (log.includes('"path":"after-preview.txt"') && log.endsWith("\n")) return true;
		}
		return false;
	}).toBe(true);
	await expect.poll(async () => electronApp!.evaluate(() => typeof (globalThis as typeof globalThis & { cloudUploadControl: { fail?: () => void } }).cloudUploadControl.fail === "function")).toBe(true);
	await electronApp!.evaluate(() => { (globalThis as typeof globalThis & { cloudUploadControl: { fail: () => void } }).cloudUploadControl.fail(); });
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("failed");
	expect((await page.evaluate(() => window.loom.getCloudBackup())).job?.error).toContain("cloud-note.md");
	await electronApp!.evaluate(() => { (globalThis as typeof globalThis & { cloudUploadControl: { suffix?: string } }).cloudUploadControl.suffix = undefined; });
	await localStatus.getByRole("button", { name: "Retry", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).libraries[0]?.revision).not.toBe(previous.revision);
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("completed");
	expect(await electronApp!.evaluate(() => (globalThis as typeof globalThis & { cloudUploadControl: { uploaded: string[] } }).cloudUploadControl.uploaded.filter((key) => key.endsWith("/after-preview.txt")).length)).toBe(1);
	keys = await electronApp!.evaluate(() => [...(globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects.keys()]);
	expect(keys).not.toContain(`${remoteRoot}obsolete.md`);
	await settings.getByRole("button", { name: "Refresh", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("completed");
	await expect(settings.locator(".cloud-library")).toHaveCount(1);
	await settings.getByRole("button", { name: "Restore to new folder", exact: true }).click();
	await expect(settings.getByRole("button", { name: "Open restored library", exact: true })).toBeVisible();
	const restored = (await page.evaluate(() => window.loom.getCloudBackup())).job!.restoredPath!;
	expect(restored).not.toBe(root);
	expect(await readFile(join(restored, "cloud-note.md"), "utf8")).toBe("latest cloud copy");
	expect(await readFile(join(restored, "after-preview.txt"), "utf8")).toBe("written after checking");
	await settings.getByRole("button", { name: "Open restored library", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getLibrarySnapshot())).rootPath).toBe(restored);
	const snapshot = await page.evaluate(() => window.loom.getLibrarySnapshot());
	expect(snapshot.favoriteAssetIds).toContain(assetId);
	expect(snapshot.tags.map((tag) => tag.name)).toContain("cloud-test");
	// A snapshot error must reopen both databases and leave the current library usable.
	const identity = join(restored, ".loom/backup/identity.json");
	const originalIdentity = await readFile(identity);
	await writeFile(identity, '{"id":"invalid"}');
	await settings.getByRole("button", { name: "Update cloud copy", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("failed");
	await expect(localStatus.getByRole("button", { name: "Retry", exact: true })).toBeVisible();
	expect((await page.evaluate(() => window.loom.getLibrarySnapshot())).rootPath).toBe(restored);
	await page.evaluate((id) => window.loom.setFavorite(id, false), assetId);
	expect((await page.evaluate(() => window.loom.getLibrarySnapshot())).favoriteAssetIds).not.toContain(assetId);
	await writeFile(identity, originalIdentity);
	// Simulate another computer advancing the same library, including a different metadata set.
	await page.evaluate((id) => window.loom.addAssetTag(id, "local-only"), assetId);
	await writeFile(join(restored, "cloud-note.md"), "keep this local edit");
	await electronApp!.evaluate((_electron, remoteRoot) => {
		const { createHash, randomUUID } = process.getBuiltinModule("node:crypto");
		const g = globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer>; cloudSavedCopy: Map<string, Buffer> };
		const key = `${remoteRoot}.loom/backup/manifest.json`;
		const current = JSON.parse(g.cloudObjects.get(key)!.toString()), saved = JSON.parse(g.cloudSavedCopy.get(key)!.toString());
		current.files = current.files.filter((file: { path: string }) => !file.path.startsWith(".loom/") && file.path !== "after-preview.txt");
		current.files.push(...saved.files.filter((file: { path: string }) => file.path.startsWith(".loom/")));
		current.directories = [...current.directories.filter((path: string) => path !== ".loom" && !path.startsWith(".loom/")), ...saved.directories.filter((path: string) => path === ".loom" || path.startsWith(".loom/"))];
		for (const file of saved.files.filter((file: { path: string }) => file.path.startsWith(".loom/"))) g.cloudObjects.set(`${remoteRoot}${file.path}`, g.cloudSavedCopy.get(`${remoteRoot}${file.path}`)!);
		g.cloudObjects.delete(`${remoteRoot}after-preview.txt`);
		for (const [path, content] of [["cloud-note.md", "changed on other device"], ["cloud-added.txt", "new from cloud"]]) {
			const bytes = Buffer.from(content!), hash = createHash("sha256").update(bytes).digest("hex");
			current.files = current.files.filter((file: { path: string }) => file.path !== path);
			current.files.push({ path, size: bytes.length, hash, etag: hash, mtimeMs: Date.now() }); g.cloudObjects.set(`${remoteRoot}${path}`, bytes);
		}
		current.library = { ...current.library, revision: randomUUID(), fileCount: current.files.length, totalBytes: current.files.reduce((sum: number, file: { size: number }) => sum + file.size, 0), updatedAt: new Date().toISOString() };
		const bytes = Buffer.from(JSON.stringify(current)); g.cloudObjects.set(key, bytes);
		g.cloudObjects.set(`loom/.loom/libraries/${current.library.libraryId}.json`, Buffer.from(JSON.stringify({ ...current.library, state: "ready", manifestHash: createHash("sha256").update(bytes).digest("hex") })));
	}, remoteRoot);
	await settings.getByRole("button", { name: "Pull cloud changes", exact: true }).click();
	const pull = settings.getByRole("region", { name: "Changes to apply locally", exact: true });
	await expect(pull).toBeVisible();
	const apply = pull.getByRole("button", { name: "Apply to current library", exact: true });
	await expect(apply).toBeDisabled();
	await pull.getByRole("button", { name: "Use cloud for all conflicts", exact: true }).click();
	await pull.locator("li").filter({ hasText: "cloud-note.md" }).getByRole("radio", { name: "Keep local", exact: true }).check();
	await expect(apply).toBeEnabled();
	await page.screenshot({ path: test.info().outputPath("cloud-pull-conflicts.png") });
	await apply.click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("completed");
	expect((await page.evaluate(() => window.loom.getLibrarySnapshot())).rootPath).toBe(restored);
	expect(await readFile(join(restored, "cloud-note.md"), "utf8")).toBe("keep this local edit");
	expect(await readFile(join(restored, "cloud-added.txt"), "utf8")).toBe("new from cloud");
	expect(await readdir(restored)).not.toContain("after-preview.txt");
	const pulled = await page.evaluate(() => window.loom.getLibrarySnapshot());
	expect(pulled.favoriteAssetIds).toContain(assetId);
	expect(pulled.tags.map((tag) => tag.name)).toContain("cloud-test");
	expect(pulled.tags.map((tag) => tag.name)).not.toContain("local-only");
	// A valid transfer containing an unusable database must roll the directory back.
	await electronApp!.evaluate((_electron, remoteRoot) => {
		const { createHash, randomUUID } = process.getBuiltinModule("node:crypto");
		const g = globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer>; cloudValidCopy: Map<string, Buffer> };
		g.cloudValidCopy = new Map(g.cloudObjects);
		const key = `${remoteRoot}.loom/backup/manifest.json`, manifest = JSON.parse(g.cloudObjects.get(key)!.toString());
		const file = manifest.files.find((file: { path: string }) => file.path === ".loom/metadata-db/metadata.db");
		const invalid = Buffer.from("an invalid SQLite database");
		Object.assign(file, { hash: createHash("sha256").update(invalid).digest("hex"), size: invalid.length, mtimeMs: Date.now() }); file.etag = file.hash;
		g.cloudObjects.set(`${remoteRoot}${file.path}`, invalid);
		manifest.library = { ...manifest.library, revision: randomUUID(), totalBytes: manifest.files.reduce((sum: number, file: { size: number }) => sum + file.size, 0) };
		const bytes = Buffer.from(JSON.stringify(manifest)); g.cloudObjects.set(key, bytes);
		g.cloudObjects.set(`loom/.loom/libraries/${manifest.library.libraryId}.json`, Buffer.from(JSON.stringify({ ...manifest.library, state: "ready", manifestHash: createHash("sha256").update(bytes).digest("hex") })));
	}, remoteRoot);
	await settings.getByRole("button", { name: "Pull cloud changes", exact: true }).click();
	await expect(pull).toBeVisible();
	await pull.getByRole("button", { name: "Use cloud for all conflicts", exact: true }).click();
	await apply.click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("failed");
	expect((await page.evaluate(() => window.loom.getLibrarySnapshot())).rootPath).toBe(restored);
	expect(await readFile(join(restored, "cloud-note.md"), "utf8")).toBe("keep this local edit");
	expect((await page.evaluate(() => window.loom.getLibrarySnapshot())).favoriteAssetIds).toContain(assetId);
	await electronApp!.evaluate(() => { const g = globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer>; cloudValidCopy: Map<string, Buffer> }; g.cloudObjects.clear(); for (const [key, bytes] of g.cloudValidCopy) g.cloudObjects.set(key, bytes); });
	// Leaving an awaiting pull cancels it and resumes the current library.
	await settings.getByRole("button", { name: "Pull cloud changes", exact: true }).click();
	await expect(pull).toBeVisible();
	await settings.getByRole("button", { name: "Close settings", exact: true }).click();
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).job?.status).toBe("cancelled");
	await page.evaluate((id) => window.loom.setFavorite(id, false), assetId);
	await page.getByRole("button", { name: "Settings", exact: true }).click();
	await settings.getByRole("tab", { name: "Cloud backup", exact: true }).click();
	const objectsBeforeDisable = await electronApp!.evaluate(() => [...(globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects.keys()]);
	await provider.selectOption("none");
	await settings.getByRole("button", { name: "Save", exact: true }).click();
	await expect(settings.getByRole("button", { name: "Update cloud copy", exact: true })).toHaveCount(0);
	await expect(settings.getByLabel("SecretId", { exact: true })).toHaveCount(0);
	await expect.poll(async () => (await page.evaluate(() => window.loom.getCloudBackup())).hasCredentials).toBe(false);
	await page.reload();
	await page.getByRole("button", { name: "Settings", exact: true }).click();
	await settings.getByRole("tab", { name: "Cloud backup", exact: true }).click();
	await expect(provider).toHaveValue("none");
	await provider.selectOption("cos");
	await expect(settings.getByLabel("Bucket", { exact: true })).toHaveValue("my-loom-1250000000");
	await expect(settings.getByLabel("SecretKey", { exact: true })).toHaveValue("e2e-secret-key-updated");
	await settings.getByRole("button", { name: "Save", exact: true }).click();
	await expect(settings.getByRole("button", { name: "Update cloud copy", exact: true })).toBeEnabled();
	expect((await page.evaluate(() => window.loom.getCloudBackup())).localLibrary?.rootPath).toBe(restored);
	expect(await electronApp!.evaluate(() => [...(globalThis as typeof globalThis & { cloudObjects: Map<string, Buffer> }).cloudObjects.keys()])).toEqual(objectsBeforeDisable);
});
